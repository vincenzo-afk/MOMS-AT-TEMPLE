// Builds public/assets/models/manifest.json from Blender export reports (blender/export_reports/*.json).
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const reportDir = join(root, "blender/export_reports");
const TYPE_BY_DIR = { environment: "environment", landmarks: "landmark", buildings: "building", props: "prop", characters: "character" };

const assets = [];
for (const f of readdirSync(reportDir).sort()) {
  if (!f.endsWith(".json") || f === "last_build.json" || f === "glb_validation.json" || f.startsWith("TEST_")) continue;
  const r = JSON.parse(readFileSync(join(reportDir, f), "utf8"));
  if (typeof r.glb !== "string") continue; // not an export report (e.g. reference-scene measurements)
  const sub = r.glb.split("/")[3];
  const type = TYPE_BY_DIR[sub];
  if (!type) continue;
  if (!existsSync(join(root, r.glb))) {
    console.warn(`skip ${r.assetId}: ${r.glb} missing`);
    continue;
  }
  const entry = {
    id: r.assetId,
    url: "/" + r.glb.replace(/^public\//, ""),
    type,
    triangles: r.triangles,
    bytes: existsSync(join(root, r.glb)) ? statSync(join(root, r.glb)).size : r.bytes, // after post-export optimisation
    expect: {
      nodes: (r.colliders ?? []).slice(0, 3),
      // the player GLB is also the shared animation library (every clip, every bone)
      maxBytes: type === "landmark" || r.clips ? 1_500_000 : 800_000,
      maxTriangles: type === "landmark" ? 40_000 : 12_000,
    },
  };
  if (r.clips) {
    entry.clips = r.clips;
    entry.expect.animations = r.clips.map((c) => c.name);
    entry.expect.skinned = true;
  }
  assets.push(entry);
}
writeFileSync(join(root, "public/assets/models/manifest.json"), JSON.stringify({ generatedAt: new Date().toISOString(), assets }, null, 2));
console.log(`manifest: ${assets.length} models`);

// ---- human-readable manifest (docs/ASSET_MANIFEST.md) - regenerated, do not edit by hand
const NOTES = {
  character: "procedural first pass; rig SK_Humanoid_A; 11 clips",
  landmark: "hero asset; front faces +Z",
};
const rows = assets.map((a) => {
  const r = JSON.parse(readFileSync(join(reportDir, `${a.id}.json`), "utf8"));
  const size = r.boundsMin && r.boundsMax ? r.boundsMax.map((v, i) => (v - r.boundsMin[i]).toFixed(2)).join(" x ") : "";
  const deps = (r.materials ?? []).join(", ");
  const status = "verified";
  return `| ${a.id} | ${a.type} | \`${r.blend}\` | \`public${a.url}\` | ${a.triangles.toLocaleString("en")} | ${(a.bytes / 1024).toFixed(0)} kB | ${size} | ${deps} | ${NOTES[a.type] ?? ""} | ${status} |`;
});
